#!/usr/bin/env python3
"""gen_timing.py <script_marked.md> <whisper words.txt> <tempo> <out timing.ts> [lead_s]

Fits the script's words to Whisper's word times (difflib on normalised tokens, unmatched words
interpolated between their matched neighbours), divides by the atempo factor, adds a lead-in, and
writes a TypeScript module the chalk film imports: per line its start/end and every word's
text, keyword flag and start/end in seconds."""
import difflib, json, re, sys

script, words_txt, tempo, out = sys.argv[1], sys.argv[2], float(sys.argv[3]), sys.argv[4]
lead = float(sys.argv[5]) if len(sys.argv) > 5 else 0.0
norm = lambda s: re.sub(r"[^a-z0-9]", "", s.lower().replace("%", "percent"))

lines = []
for raw in open(script, encoding="utf-8"):
    m = re.match(r"^([A-Z]+):\s*(.*)$", raw.strip())
    if not m: continue
    toks, key = [], False
    for tok in m.group(2).split():
        k0 = tok.startswith("*") or key
        key = k0 and not tok.rstrip(".,?!:;…").endswith("*")
        if tok.startswith("*") and tok.rstrip(".,?!:;…").endswith("*"): key = False
        toks.append({"t": tok.replace("*", ""), "key": k0})
    lines.append(toks)

# whisper words; join number pieces ("1.2", "%") so they match the script tokens
wh = []
for l in open(words_txt, encoding="utf-8"):
    p = l.split(None, 2)
    if len(p) == 3: wh.append([float(p[0]), float(p[1]), p[2].strip()])
merged = []
for w in wh:
    if merged and (norm(w[2]) in ("percent", "") or w[2].strip() in ("%",)) and re.search(r"\d", merged[-1][2]):
        merged[-1][1] = w[1]; merged[-1][2] += w[2].strip(); continue
    merged.append(w)

flat = [(li, wi, w) for li, ln in enumerate(lines) for wi, w in enumerate(ln)]
spoken = {"12%": "12percent", "100": "100", "90": "90", "1%": "1percent", "1.2%": "12percent", "2016": "2016"}
def sn(t):
    n = norm(t)
    return n
a = [sn(w["t"]) for _, _, w in flat]
# whisper writes numbers as digits ("12%", "$1.2") — normalise both sides the same way
b = [norm(w[2]) for w in merged]
times = [None] * len(flat)
for blk in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks():
    for k in range(blk.size): times[blk.a + k] = (merged[blk.b + k][0], merged[blk.b + k][1])
# interpolate the gaps
matched = [i for i, t in enumerate(times) if t]
for i in range(len(times)):
    if times[i]: continue
    lo = max([j for j in matched if j < i], default=None); hi = min([j for j in matched if j > i], default=None)
    t0 = times[lo][1] if lo is not None else 0.0
    t1 = times[hi][0] if hi is not None else (times[lo][1] + 0.5 if lo is not None else 0.5)
    n = (hi if hi is not None else len(times)) - (lo if lo is not None else -1)
    k = i - (lo if lo is not None else -1)
    s = t0 + (t1 - t0) * (k - 1) / n * 1.0; e = t0 + (t1 - t0) * k / n
    times[i] = (s, e)
miss = len(times) - len(matched)

res = []
for li, ln in enumerate(lines):
    ws = []
    for wi, w in enumerate(ln):
        s, e = times[[i for i, (l2, w2, _) in enumerate(flat) if l2 == li and w2 == wi][0]]
        ws.append({"t": w["t"], "key": w["key"], "s": round(s / tempo + lead, 3), "e": round(e / tempo + lead, 3)})
    res.append({"s": ws[0]["s"], "e": ws[-1]["e"], "words": ws})
open(out, "w").write("// generated by gen_timing.py — do not edit\nexport type TWord = { t: string; key: boolean; s: number; e: number };\nexport const LINES: { s: number; e: number; words: TWord[] }[] = " + json.dumps(res) + ";\n")
print(f"{len(flat)} script words, {len(matched)} matched, {miss} interpolated; end {res[-1]['e']:.2f}s")
